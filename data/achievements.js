/**
 * achievements.js – registr všech in-game úspěchů (v1.6.0, rework).
 *
 * Nový model (Steam styl): { id, name, hint, condition, tier, check, reward }
 *  - name      … vtipný název (skrytý dokud není odemčeno → v UI „???")
 *  - hint      … kryptická, absurdní hláška ZOBRAZENÁ VŽDY (i u zamčeného;
 *                hráč z ní hádá, co má udělat). Po odemčení je to druhá pointa.
 *  - condition … prostý text „co se reálně muselo stát" (odhalí se AŽ po
 *                odemčení, řádek „Unlocked for: …" – hráč konečně vidí důvod).
 *  - tier      … "common" | "secret" | "rare" | "insane" (jen vizuální třída)
 *  - check(d)  … funkce vracející boolean; d jsou odvozené staty (viz
 *                achievementSystem.deriveStats – dexCount, owned Set, countery…)
 *  - reward    … { gold?, coins?, items?: { itemId: qty } }
 *
 *  BEZ ikon (záměrně – hra achievementy zobrazuje čistě textově).
 *  Odemčení je perzistentní (state.achievements.unlocked[id] = timestamp) a
 *  odměna se přidělí JEN JEDNOU. Humor: absurdní, deadpan, „unavený vývojář".
 */

