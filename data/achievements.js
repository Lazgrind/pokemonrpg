// GENERATIONS, takže gen3–9 ho dostanou automaticky bez sahání sem. Stabilní id
// kvůli save kompatibilitě (starý „dex-151" musí zůstat gen1); nové generace
// dostanou „dex-complete-gen<N>". Check jede přes d.dexGenComplete[gen] (viz
// achievementSystem.deriveStats). V produkci (GEN2_ENABLED=false) má GENERATIONS
// jen gen1 → žádný johtský achievement se neukáže (gen2 je skrytá).
const DEX_COMPLETE_ID = { 1: "dex-151", 2: "dex-251" };
const DEX_COMPLETE_META = {
  1: { name: "Professor Oak Is Blocking Your Number", hint: "Please stop sending him updates." },
  2: { name: "Professor Elm Joined The Block List", hint: "That's two professors now. Impressive." },
};
const DEX_COMPLETE_ACHIEVEMENTS = GENERATIONS.map((g) => {
  const meta = DEX_COMPLETE_META[g.gen] ?? {};
  return {
    id: DEX_COMPLETE_ID[g.gen] ?? `dex-complete-gen${g.gen}`,
    name: meta.name ?? `The ${g.regionName} Completionist`,
    hint: meta.hint ?? "Somewhere a professor is updating your file.",
    condition: `Register all ${g.regionName} species.`,
    tier: "common",
    check: (d) => !!d.dexGenComplete?.[g.gen],
    reward: { gold: 5000, coins: 50 },
  };
});

